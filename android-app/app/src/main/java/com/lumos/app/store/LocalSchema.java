/*
 * Lumos - android-app/app / Canonical local schema and its forward-only migrations.
 * Author: dhar.abhishek.email@gmail.com
 * Implements: TRS-LOC-002, TRS-LOC-003, TRS-LOC-010, SRS-DAT-002
 * ADRs: ADR-003
 * Threading: any
 * Notes: Every table has the SAME shape, and that uniformity is a privacy
 * decision rather than a convenience. A row is an opaque id, an AEAD-sealed
 * payload, an optional blind-index tag, and UTC timestamps - so the schema
 * itself carries no content. Threat model LT-16: a column named
 * `orientation_gay` leaks to anyone who reads the file header, and no amount of
 * value encryption fixes a revealing schema. The cost is that SQL cannot filter
 * on sealed fields; lookups go through the blind index (SealedRecordCodec) and
 * everything else is decrypt-then-filter in the domain layer.
 *
 * The DDL is written out rather than generated by an ORM because it is the
 * artefact the migration suite EXECUTES, on both platforms, against a real
 * SQLite engine. Swift declares the same schema in LocalSchema.swift and
 * tools/schemacheck fails the build if the two ever disagree.
 *
 * Not Room, and that is a stated deviation from TRS-AND-004 rather than an
 * oversight - see the pull request. Room generates its DDL at compile time and
 * verifies migrations only under an instrumented test on a device or emulator,
 * neither of which CI has; nothing about the storage layer would then be
 * executed by any gate. This seam runs the same SQL under JDBC in CI and under
 * android.database.sqlite on a device. Room can be layered on this schema later
 * without changing a byte of it.
 */

package com.lumos.app.store;

import java.util.ArrayList;
import java.util.Collections;
import java.util.List;

/** The local database schema: table names, DDL and the migration ladder. */
public final class LocalSchema {

    /** The schema version this build writes and expects. */
    public static final int VERSION = 7;

    /** The version of an absent or empty database, before any migration runs. */
    public static final int VERSION_EMPTY = 0;

    /** Table holding the schema version and nothing else. */
    public static final String TABLE_META = "lumos_meta";

    /** The meta table's single-row key column. */
    public static final String META_KEY = "meta_key";

    /** The meta table's value column. */
    public static final String META_VALUE = "meta_value";

    /** Meta key under which the schema version is stored. */
    public static final String META_SCHEMA_VERSION = "schema_version";

    /** Opaque stable row identifier (TRS-LOC-010: a UUID, never a natural key). */
    public static final String COLUMN_ID = "id";

    /** The AEAD-sealed record payload. */
    public static final String COLUMN_PAYLOAD = "payload";

    /** Blind-index tag for lookups by a natural key that must not be stored. */
    public static final String COLUMN_LOOKUP_TAG = "lookup_tag";

    /** Creation time, UTC milliseconds since the epoch (TRS-LOC-010). */
    public static final String COLUMN_CREATED_AT = "created_at";

    /** Last-update time, UTC milliseconds since the epoch (TRS-LOC-010). */
    public static final String COLUMN_UPDATED_AT = "updated_at";

    /** The schema version that sealed this row's payload, for forward reads. */
    public static final String COLUMN_PAYLOAD_VERSION = "payload_version";

    private LocalSchema() {
        throw new AssertionError("no instances");
    }

    /**
     * The DDL creating one record table.
     *
     * @param table the table name
     * @return the CREATE TABLE statement
     */
    public static String createRecordTable(final String table) {
        return "CREATE TABLE " + table + " ("
                + COLUMN_ID + " TEXT PRIMARY KEY NOT NULL, "
                + COLUMN_PAYLOAD + " BLOB NOT NULL, "
                + COLUMN_LOOKUP_TAG + " BLOB, "
                + COLUMN_CREATED_AT + " INTEGER NOT NULL, "
                + COLUMN_UPDATED_AT + " INTEGER NOT NULL, "
                + COLUMN_PAYLOAD_VERSION + " INTEGER NOT NULL)";
    }

    /**
     * The DDL creating one table's blind-index lookup index.
     *
     * @param table the table name
     * @return the CREATE INDEX statement
     */
    public static String createLookupIndex(final String table) {
        return "CREATE INDEX idx_" + table + "_lookup ON " + table + " (" + COLUMN_LOOKUP_TAG + ")";
    }

    /**
     * The record kinds version 1 created, frozen as a literal list.
     *
     * <p>It is a list and not {@code RecordKind.values()} on purpose, and the
     * difference is the whole of TRS-LOC-003. A past migration describes what
     * a past build DID; deriving it from today's enum rewrites history, so
     * adding a kind would silently make step 0-to-1 create the new table and
     * then step 1-to-2 would fail on a fresh database while succeeding on an
     * upgraded one. Every step below therefore names its own tables, and a
     * kind added later joins a new step, never an existing one.
     */
    private static final List<RecordKind> VERSION_1_KINDS = List.of(
            RecordKind.IDENTITY_KEY_RECORD,
            RecordKind.RECOVERY_RECORD,
            RecordKind.LOCAL_PROFILE,
            RecordKind.PROFILE_FIELD_POLICY,
            RecordKind.PROFILE_MEDIA,
            RecordKind.BLOCK_ENTRY,
            RecordKind.DIAGNOSTIC_EVENT);

    /** The record kinds version 2 added (WP-02 slice S4c). */
    private static final List<RecordKind> VERSION_2_KINDS = List.of(
            RecordKind.CONSENT_RECORD,
            RecordKind.DISCOVERY_VISIBILITY);

    /** The record kinds version 3 added (WP-03 slice S5b). */
    private static final List<RecordKind> VERSION_3_KINDS = List.of(
            RecordKind.APP_LOCK);

    /** The record kinds version 4 added (WP-04 slice S1a). */
    private static final List<RecordKind> VERSION_4_KINDS = List.of(
            RecordKind.HIDDEN_PEER);

    /** The record kinds version 5 added (WP-04 slice S3). */
    private static final List<RecordKind> VERSION_5_KINDS = List.of(
            RecordKind.INTEREST_RECORD, RecordKind.MATCH_RECORD,
            RecordKind.INTEREST_BUDGET);

    /** The record kinds version 6 added (WP-05 S7b). */
    private static final List<RecordKind> VERSION_6_KINDS = List.of(
            RecordKind.CONVERSATION, RecordKind.CHAT_MESSAGE, RecordKind.OUTBOX_ITEM,
            RecordKind.RATCHET_SESSION, RecordKind.MESSAGE_DEDUP, RecordKind.PREKEY_SECRET);

    /** The record kinds version 7 added (WP-05 S7c). */
    private static final List<RecordKind> VERSION_7_KINDS = List.of(RecordKind.RELAY_ACCOUNT);

    /**
     * The complete statement list taking an empty database to version 1.
     *
     * <p>Order matters and is asserted: the meta table exists before anything
     * writes a version into it.
     *
     * @return the ordered statements of migration 0 to 1
     */
    public static List<String> migrationToVersion1() {
        final List<String> statements = new ArrayList<>();
        statements.add("CREATE TABLE " + TABLE_META + " ("
                + META_KEY + " TEXT PRIMARY KEY NOT NULL, "
                + META_VALUE + " TEXT NOT NULL)");
        statements.addAll(createTablesFor(VERSION_1_KINDS));
        return Collections.unmodifiableList(statements);
    }

    /**
     * The statements taking a version-1 database to version 2.
     *
     * <p>Two new tables and nothing else. No existing table is altered and no
     * row is rewritten, so an interrupted upgrade leaves a version-1 database
     * rather than a half-converted one.
     *
     * @return the ordered statements of migration 1 to 2
     */
    public static List<String> migrationToVersion2() {
        return Collections.unmodifiableList(createTablesFor(VERSION_2_KINDS));
    }

    /**
     * The statements taking a version-2 database to version 3.
     *
     * <p>One new table and nothing else, the same interruption-safe shape as
     * the step before it: an upgrade that stops half way leaves a version-2
     * database, never a half-converted one.
     *
     * @return the ordered statements of migration 2 to 3
     */
    public static List<String> migrationToVersion3() {
        return Collections.unmodifiableList(createTablesFor(VERSION_3_KINDS));
    }

    /**
     * The statements taking a version-3 database to version 4.
     *
     * <p>One new table and nothing else, the interruption-safe shape every
     * step of this ladder keeps.
     *
     * @return the ordered statements of migration 3 to 4
     */
    public static List<String> migrationToVersion4() {
        return Collections.unmodifiableList(createTablesFor(VERSION_4_KINDS));
    }

    /**
     * The statements taking a version-4 database to version 5.
     *
     * <p>Three new tables and nothing else - the interruption-safe shape
     * every step of this ladder keeps.
     *
     * @return the ordered statements of migration 4 to 5
     */
    public static List<String> migrationToVersion5() {
        return Collections.unmodifiableList(createTablesFor(VERSION_5_KINDS));
    }

    /**
     * The statements taking a version-5 database to version 6.
     *
     * <p>Six new tables for the chat path and nothing else - the
     * interruption-safe shape every step of this ladder keeps.
     *
     * @return the ordered statements of migration 5 to 6
     */
    public static List<String> migrationToVersion6() {
        return Collections.unmodifiableList(createTablesFor(VERSION_6_KINDS));
    }

    /**
     * The statements taking a version-6 database to version 7.
     *
     * <p>One new table for the relay registration and nothing else.
     *
     * @return the ordered statements of migration 6 to 7
     */
    public static List<String> migrationToVersion7() {
        return Collections.unmodifiableList(createTablesFor(VERSION_7_KINDS));
    }

    /**
     * The create-table and create-index pair for each of the given kinds.
     *
     * @param kinds the kinds a migration step introduces
     * @return the ordered statements
     */
    private static List<String> createTablesFor(final List<RecordKind> kinds) {
        final List<String> statements = new ArrayList<>();
        for (final RecordKind kind : kinds) {
            statements.add(createRecordTable(kind.table()));
            statements.add(createLookupIndex(kind.table()));
        }
        return statements;
    }

    /**
     * The forward-only migration ladder.
     *
     * <p>Forward-only is the whole design (TRS-LOC-003). There is no downgrade
     * path and there will never be one: a downgrade would have to discard data
     * the newer version wrote, which on this schema means discarding sealed
     * payloads nobody can inspect first. A database from the future is refused,
     * not "handled".
     *
     * @return every migration, in ascending version order
     */
    public static List<Migration> migrations() {
        final List<Migration> ladder = new ArrayList<>();
        ladder.add(new Migration(VERSION_EMPTY, 1, migrationToVersion1()));
        ladder.add(new Migration(1, 2, migrationToVersion2()));
        ladder.add(new Migration(2, 3, migrationToVersion3()));
        ladder.add(new Migration(3, 4, migrationToVersion4()));
        ladder.add(new Migration(4, 5, migrationToVersion5()));
        ladder.add(new Migration(5, 6, migrationToVersion6()));
        ladder.add(new Migration(6, 7, migrationToVersion7()));
        return Collections.unmodifiableList(ladder);
    }
}
