// Lumos - tools/sbomgen / CycloneDX SBOM stub for the current dependency set.
// Author: dhar.abhishek.email@gmail.com
// Implements: TRS-CICD-004, TRS-REP-003
// ADRs: -
// Threading: main-safe
// Notes: A STUB, and labelled as one in the document it emits. It reads the
// dependency sets this repository actually locks - go.mod/go.sum, the Gradle
// version catalogue, the npm lockfile - and emits CycloneDX 1.5. What it does
// NOT do is resolve transitive dependencies or attach provenance attestations,
// both of which TRS-CICD-004 requires at release. Emitting a document that
// merely looks like a release SBOM would be worse than emitting none, so the
// gaps are declared inside the artefact where a consumer cannot miss them.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/dharabhishekorg/lumos/tools/deplock"
)

// Component is one CycloneDX component entry.
type Component struct {
	Type       string `json:"type"`
	Name       string `json:"name"`
	Version    string `json:"version"`
	PURL       string `json:"purl,omitempty"`
	Scope      string `json:"scope,omitempty"`
	Licenses   []any  `json:"licenses,omitempty"`
	Ecosystem  string `json:"x-ecosystem"`
	SourceFile string `json:"x-locked-in"`
	// LicenseNote is set only when no licence could be established, so an
	// absent licence reads as an absence rather than as permissiveness.
	LicenseNote string `json:"x-license-note,omitempty"`
}

// SBOM is the emitted CycloneDX 1.5 document.
type SBOM struct {
	BOMFormat   string         `json:"bomFormat"`
	SpecVersion string         `json:"specVersion"`
	Version     int            `json:"version"`
	Metadata    map[string]any `json:"metadata"`
	Components  []Component    `json:"components"`
	Limitations []string       `json:"x-stub-limitations"`
}

func main() {
	var (
		root = flag.String("root", ".", "repository root")
		out  = flag.String("out", "evidence/sbom/lumos-sbom.json", "output path")
	)
	flag.Parse()
	if err := run(*root, *out); err != nil {
		fmt.Fprintln(os.Stderr, "sbomgen:", err)
		os.Exit(1)
	}
}

func run(root, out string) error {
	var components []Component

	goComponents, err := goModules(root)
	if err != nil {
		return err
	}
	components = append(components, goComponents...)

	components = append(components, gradleComponents(root)...)

	npmComponents, err := npmComponents(root)
	if err != nil {
		return err
	}
	components = append(components, npmComponents...)

	// SwiftPM joined the SBOM in WP-02 S4b, when the package gained its first
	// external dependency. A stub that silently omitted an ecosystem would be
	// worse than one that says it is a stub.
	swiftComponents, err := swiftPMComponents(root)
	if err != nil {
		return err
	}
	components = append(components, swiftComponents...)

	// Licences come from the toolchain manifest rather than from the lockfiles,
	// which do not carry them. tools/deplock asserts by test that the manifest
	// and the lockfiles agree, so this is not a second source of truth - it is
	// the same one, joined on the module path.
	licences, err := manifestLicences(root)
	if err != nil {
		return err
	}
	for i := range components {
		if lic := licences[components[i].Name]; lic != "" {
			components[i].Licenses = []any{map[string]any{
				"license": map[string]string{"id": lic},
			}}
		} else {
			components[i].LicenseNote = "not declared in the toolchain manifest"
		}
	}

	sort.Slice(components, func(i, j int) bool {
		if components[i].Ecosystem != components[j].Ecosystem {
			return components[i].Ecosystem < components[j].Ecosystem
		}
		return components[i].Name < components[j].Name
	})

	doc := SBOM{
		BOMFormat:   "CycloneDX",
		SpecVersion: "1.5",
		Version:     1,
		Metadata: map[string]any{
			"component": map[string]any{
				"type": "application",
				"name": "lumos",
			},
			"tools": []map[string]string{{"name": "tools/sbomgen", "version": "wp-01"}},
			"x-note": "STUB. Generated by WP-01 slice S7 from the repository's own " +
				"lockfiles. Not a release SBOM.",
		},
		Components: components,
		Limitations: []string{
			"Direct dependencies only: transitive closures are not resolved.",
			"No cryptographic hashes per component; the lockfiles hold the checksums.",
			"No provenance or attestation (TRS-CICD-004 requires both at release).",
			"Android and Swift transitive graphs are not walked; only the pinned direct versions are listed.",
			"A release SBOM is produced by WP-11, which owns the signing and provenance chain.",
		},
	}

	raw, err := json.MarshalIndent(doc, "", " ")
	if err != nil {
		return err
	}
	target := filepath.FromSlash(out)
	if !filepath.IsAbs(target) {
		target = filepath.Join(root, target)
	}
	if err := os.MkdirAll(filepath.Dir(target), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(target, append(raw, '\n'), 0o644); err != nil {
		return err
	}
	fmt.Printf("wrote %s: %d components across %d ecosystems (STUB)\n",
		out, len(components), countEcosystems(components))
	return nil
}

// manifestLicences maps a module path to its declared SPDX licence.
func manifestLicences(root string) (map[string]string, error) {
	m, err := deplock.LoadManifest(root)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	for _, d := range m.GoDependencies.Modules {
		out[d.Path] = d.License
	}
	for _, d := range m.JVMTestDependencies.Modules {
		out[d.Path] = d.License
	}
	for _, d := range m.BuildDependencies.Modules {
		out[d.Path] = d.License
	}
	for _, d := range m.NPMDependencies.Modules {
		out[d.Path] = d.License
	}
	for _, d := range m.RuntimeDependencies.Modules {
		out[d.Path] = d.License
	}
	for _, d := range m.SwiftPMDependencies.Modules {
		out[d.Path] = d.License
	}
	return out, nil
}

func countEcosystems(cs []Component) int {
	seen := map[string]bool{}
	for _, c := range cs {
		seen[c.Ecosystem] = true
	}
	return len(seen)
}

// goModules reads the direct requirements from go.mod.
func goModules(root string) ([]Component, error) {
	raw, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return nil, fmt.Errorf("read go.mod: %w", err)
	}
	var out []Component
	for _, line := range strings.Split(string(raw), "\n") {
		fields := strings.Fields(strings.TrimSpace(line))
		if len(fields) < 2 {
			continue
		}
		if fields[0] == "require" && len(fields) >= 3 {
			fields = fields[1:]
		}
		if !strings.Contains(fields[0], "/") || !strings.HasPrefix(fields[1], "v") {
			continue
		}
		scope := "required"
		if strings.Contains(line, "// indirect") {
			scope = "optional"
		}
		out = append(out, Component{
			Type: "library", Name: fields[0], Version: fields[1],
			PURL:      "pkg:golang/" + fields[0] + "@" + fields[1],
			Scope:     scope,
			Ecosystem: "go", SourceFile: "go.mod + go.sum",
		})
	}
	return out, nil
}

// gradleComponents reads the pinned versions from the Gradle version catalogue.
func gradleComponents(root string) []Component {
	raw, err := os.ReadFile(filepath.Join(root, "gradle", "libs.versions.toml"))
	if err != nil {
		return nil
	}
	versions := map[string]string{}
	section := ""
	var out []Component
	for _, line := range strings.Split(string(raw), "\n") {
		t := strings.TrimSpace(line)
		if strings.HasPrefix(t, "[") {
			section = t
			continue
		}
		if t == "" || strings.HasPrefix(t, "#") {
			continue
		}
		if section == "[versions]" {
			k, v, ok := strings.Cut(t, "=")
			if !ok {
				continue
			}
			versions[strings.TrimSpace(k)] = strings.Trim(strings.TrimSpace(v), `"`)
			continue
		}
		if section == "[libraries]" || section == "[plugins]" {
			name, rest, ok := strings.Cut(t, "=")
			if !ok {
				continue
			}
			module := betweenQuotes(rest, "module = ")
			if module == "" {
				module = betweenQuotes(rest, "id = ")
			}
			ref := betweenQuotes(rest, "version.ref = ")
			version := versions[ref]
			if module == "" || version == "" {
				continue
			}
			out = append(out, Component{
				Type: "library", Name: module, Version: version,
				PURL:      "pkg:maven/" + strings.ReplaceAll(module, ":", "/") + "@" + version,
				Scope:     "required",
				Ecosystem: "gradle", SourceFile: "gradle/libs.versions.toml",
			})
			_ = name
		}
	}
	return out
}

func betweenQuotes(s, key string) string {
	i := strings.Index(s, key)
	if i < 0 {
		return ""
	}
	rest := s[i+len(key):]
	if !strings.HasPrefix(rest, `"`) {
		return ""
	}
	rest = rest[1:]
	j := strings.Index(rest, `"`)
	if j < 0 {
		return ""
	}
	return rest[:j]
}

// npmComponents reads the admin console's direct devDependencies.
func npmComponents(root string) ([]Component, error) {
	raw, err := os.ReadFile(filepath.Join(root, "admin-console", "package.json"))
	if err != nil {
		// An absent package.json means the admin shell is not in this checkout,
		// which is a state with no components rather than a failure.
		return nil, nil //nolint:nilerr,nilnil // absence is a meaningful, non-error state
	}
	var pkg struct {
		DevDependencies map[string]string `json:"devDependencies"`
		Dependencies    map[string]string `json:"dependencies"`
	}
	if err := json.Unmarshal(raw, &pkg); err != nil {
		return nil, fmt.Errorf("parse admin package.json: %w", err)
	}
	var out []Component
	add := func(m map[string]string, scope string) {
		for name, version := range m {
			out = append(out, Component{
				Type: "library", Name: name, Version: version,
				PURL:      "pkg:npm/" + name + "@" + version,
				Scope:     scope,
				Ecosystem: "npm", SourceFile: "admin-console/package-lock.json",
			})
		}
	}
	add(pkg.Dependencies, "required")
	add(pkg.DevDependencies, "optional")
	return out, nil
}

// swiftPMComponents reads the committed Package.resolved. The version is the
// tag; the revision is what actually pins it, so both are recorded.
func swiftPMComponents(root string) ([]Component, error) {
	pins, err := deplock.ReadSwiftPMResolved(root)
	if err != nil {
		return nil, err
	}
	out := make([]Component, 0, len(pins))
	for _, p := range pins {
		out = append(out, Component{
			Type: "library", Name: p.Location, Version: p.State.Version,
			Ecosystem: "swiftpm", SourceFile: "Package.swift + Package.resolved",
			PURL: "pkg:swift/" + p.Identity + "@" + p.State.Version,
		})
	}
	return out, nil
}
